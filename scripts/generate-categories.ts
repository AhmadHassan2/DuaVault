/** Regenerates the categories migration from the taxonomy in src/core/taxonomy.ts. */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { TAXONOMY } from "../src/core/taxonomy";

const esc = (s: string) => s.replace(/'/g, "''");
const rows = TAXONOMY.flatMap((t) =>
  t.subcategories.map((s, i) => `  ('${t.type}', '${esc(s.slug)}', '${esc(s.label)}', ${i})`),
);
const sql = `-- Generated by scripts/generate-seed.ts — do not edit by hand.
insert into public.categories (content_type, slug, label, sort_order) values
${rows.join(",\n")}
on conflict (content_type, slug) do update set label = excluded.label, sort_order = excluded.sort_order;
`;
writeFileSync(join(import.meta.dirname, "../supabase/migrations/20261025000001_categories.sql"), sql);
console.log(`Wrote ${rows.length} categories to the categories migration`);
