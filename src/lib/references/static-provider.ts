import type { ReferenceEntry, ReferenceSourceInfo } from "@/core/types";
import type { ReferenceProvider } from "@/core/verify/verify";
import { QuranMatcher, type QuranDataset } from "@/core/verify/quran-matcher";
import { ReferenceEntryMatcher } from "@/core/verify/reference-matcher";

/** Manifest written by scripts/import-references.ts. */
export interface ReferenceManifest {
  sources: Array<ReferenceSourceInfo & { file: string }>;
}

export interface DatasetStatus {
  quran: { loaded: boolean; verses: number; sourceName?: string; translationName?: string; licence?: string };
  references: ReferenceSourceInfo[];
}

async function fetchJson<T>(url: string): Promise<T | null> {
  try {
    const res = await fetch(url, { cache: "force-cache" });
    if (!res.ok) return null;
    return (await res.json()) as T;
  } catch {
    return null;
  }
}

/**
 * Loads trusted datasets from static JSON under /public/data (generated by
 * the fetch/import scripts). Loaded lazily, once, only when verification runs.
 */
export class StaticJsonReferenceProvider implements ReferenceProvider {
  private quran: Promise<QuranMatcher | null> | null = null;
  private refs: Promise<{ matcher: ReferenceEntryMatcher; sources: ReferenceSourceInfo[] } | null> | null = null;

  constructor(private readonly baseUrl = "/data") {}

  getQuranMatcher(): Promise<QuranMatcher | null> {
    this.quran ??= fetchJson<QuranDataset>(`${this.baseUrl}/quran/quran.json`).then((d) =>
      d && Array.isArray(d.verses) && d.verses.length ? new QuranMatcher(d) : null,
    );
    return this.quran;
  }

  private loadRefs() {
    this.refs ??= (async () => {
      const manifest = await fetchJson<ReferenceManifest>(`${this.baseUrl}/references/manifest.json`);
      if (!manifest?.sources?.length) return null;
      const lists = await Promise.all(
        manifest.sources.map((s) => fetchJson<ReferenceEntry[]>(`${this.baseUrl}/references/${s.file}`)),
      );
      return {
        matcher: new ReferenceEntryMatcher(lists.flatMap((l) => l ?? [])),
        sources: manifest.sources.map((s) => ({
          id: s.id,
          name: s.name,
          kind: s.kind,
          licence: s.licence,
          url: s.url,
          entryCount: s.entryCount,
          importedAt: s.importedAt,
        })),
      };
    })();
    return this.refs;
  }

  async getReferenceMatcher(): Promise<ReferenceEntryMatcher | null> {
    return (await this.loadRefs())?.matcher ?? null;
  }

  async status(): Promise<DatasetStatus> {
    const [q, r] = await Promise.all([this.getQuranMatcher(), this.loadRefs()]);
    return {
      quran: q
        ? {
            loaded: true,
            verses: q.dataset.verses.length,
            sourceName: q.dataset.sourceName,
            translationName: q.dataset.translationName,
            licence: q.dataset.licence,
          }
        : { loaded: false, verses: 0 },
      references: r?.sources ?? [],
    };
  }
}

let shared: StaticJsonReferenceProvider | null = null;
export function getReferenceProvider(): StaticJsonReferenceProvider {
  shared ??= new StaticJsonReferenceProvider();
  return shared;
}
